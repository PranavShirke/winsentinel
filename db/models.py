"""
WinSentinel - Data Models and Dataclasses.

This module defines the core data structures used across the framework:
Finding, Alert, SoftwareItem, CveCacheEntry, and Scan.
Every check in WinSentinel returns a Finding object with status pass, fail, or error.
"""

from dataclasses import dataclass, asdict
from typing import Optional, Dict, Any


@dataclass
class Finding:
    """
    Represents an audit finding generated by any collector module.

    Attributes:
        id: Primary key in the database (optional before insertion).
        scan_id: Associated scan identifier.
        module: Source module ('config', 'logs', or 'software').
        title: Human-readable title of the audit check.
        evidence: Technical details, command outputs, or registry values.
        status: Check result: 'pass', 'fail', or 'error'.
        likelihood: Likelihood rating (1-5) based on NIST SP 800-30.
        impact: Impact rating (1-5) based on NIST SP 800-30.
        risk_score: Likelihood x Impact (1-25), 0 for passing checks.
        severity: Severity band ('Critical', 'High', 'Medium', 'Low', 'Info', 'Error').
        remediation: Specific recommended steps to mitigate the risk.
    """
    title: str
    module: str
    evidence: str
    status: str
    likelihood: int = 1
    impact: int = 1
    risk_score: int = 1
    severity: str = "Info"
    remediation: str = "No remediation needed."
    id: Optional[int] = None
    scan_id: Optional[int] = None

    def to_dict(self) -> Dict[str, Any]:
        """Convert the Finding instance to a dictionary."""
        return asdict(self)


@dataclass
class Alert:
    """
    Represents a detected security incident or anomalous pattern in Windows Event Logs.

    Attributes:
        id: Primary key in the database.
        scan_id: Associated scan identifier.
        alert_type: Type of alert (e.g., 'Brute Force Attack', 'Possible Compromise').
        timestamp: ISO formatted timestamp of detection or event.
        account: Target username or SID.
        source_ip: Source IP address (if applicable / recorded in event).
        count: Number of correlated occurrences.
        severity: Incident severity ('Critical', 'High', 'Medium', 'Low').
        details: Comprehensive explanation of the detected threat.
    """
    alert_type: str
    timestamp: str
    severity: str
    details: str
    account: str = "N/A"
    source_ip: str = "N/A"
    count: int = 1
    id: Optional[int] = None
    scan_id: Optional[int] = None

    def to_dict(self) -> Dict[str, Any]:
        """Convert the Alert instance to a dictionary."""
        return asdict(self)


@dataclass
class SoftwareItem:
    """
    Represents an installed software program discovered from the Windows Registry.

    Attributes:
        id: Primary key in the database.
        scan_id: Associated scan identifier.
        name: Display name of the installed application.
        version: Version string extracted from registry.
        publisher: Software vendor or publisher name.
    """
    name: str
    version: str = "Unknown"
    publisher: str = "Unknown"
    id: Optional[int] = None
    scan_id: Optional[int] = None

    def to_dict(self) -> Dict[str, Any]:
        """Convert the SoftwareItem instance to a dictionary."""
        return asdict(self)


@dataclass
class CveCacheEntry:
    """
    Represents a cached vulnerability record retrieved from the National Vulnerability Database.

    Attributes:
        id: Primary key in the database.
        product: Normalized product name.
        version: Product version checked.
        cve_id: Common Vulnerabilities and Exposures identifier (e.g., CVE-2023-1234).
        cvss_score: CVSS v3.x base score (0.0 - 10.0).
        description: Summary description of the vulnerability.
        fetched_at: Timestamp when the CVE was cached from the NVD API.
    """
    product: str
    version: str
    cve_id: str
    cvss_score: float
    description: str
    fetched_at: str
    id: Optional[int] = None

    def to_dict(self) -> Dict[str, Any]:
        """Convert the CveCacheEntry instance to a dictionary."""
        return asdict(self)


@dataclass
class Scan:
    """
    Represents an audit scan session.

    Attributes:
        id: Primary key in the database.
        started_at: ISO timestamp when scan started.
        finished_at: ISO timestamp when scan finished.
        hostname: Name of the audited Windows host.
        posture_score: Overall security score (0-100).
        status: Current status ('running', 'completed', 'failed').
    """
    started_at: str
    hostname: str
    status: str = "running"
    finished_at: Optional[str] = None
    posture_score: Optional[int] = None
    id: Optional[int] = None

    def to_dict(self) -> Dict[str, Any]:
        """Convert the Scan instance to a dictionary."""
        return asdict(self)
